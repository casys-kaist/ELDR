"""Generate the native LaTeX signature-quality table from the six-cell data."""
import json
import math
from pathlib import Path
from statistics import fmean

ROOT = Path(__file__).resolve().parent
LABELS = {
    "binary": "Binary",
    "gate_prob_all": "Gate prob",
    "sqrt": r"$\sqrt{\mathrm{count}}$",
    "count": "Count",
    "count_idf": r"Count$\cdot$idf",
}


def main():
    rows = json.loads((ROOT / "data/rho_transform.json").read_text())
    cells = {(row["model"], row["workload"]) for row in rows}
    # Gate-logit results remain archived but are omitted from the compact table.
    assert len(cells) == 6 and len(rows) == 6 * (len(LABELS) + 1)
    assert {row["variant"] for row in rows} == set(LABELS) | {"gate_logit_all"}
    means = {}
    for variant in LABELS:
        selected = [row for row in rows if row["variant"] == variant]
        assert len(selected) == 6
        assert {(row["model"], row["workload"]) for row in selected} == cells
        assert all(math.isfinite(row["rho"]) for row in selected)
        means[variant] = fmean(row["rho"] for row in selected)
    order = sorted(means, key=means.get)
    values = [f"{means[name]:.3f}" for name in order]
    values[-1] = r"\textbf{" + values[-1] + "}"
    table = "\n".join([
        "% Generated by plots/plot_sig_transform.py; equal weight per model/workload.",
        r"\setlength{\tabcolsep}{2.25pt}",
        r"\begin{tabular}{lccccc}", r"\toprule",
        "Transform & " + " & ".join(LABELS[name] for name in order) + r" \\",
        r"\midrule",
        r"Mean $\rho$ & " + " & ".join(values) + r" \\",
        r"\bottomrule", r"\end{tabular}", "",
    ])
    (ROOT / "sig_transform_table.tex").write_text(table)
    print(json.dumps({name: means[name] for name in order}, indent=2))


if __name__ == "__main__":
    main()
